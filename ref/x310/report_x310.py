"""Stage 5 accuracy tables (all **model**: channel-model data) from the committed selection / export records.

Reads ref/x310/x310_selection.json (validation numbers for every W; test for the chosen model and its float
baseline), ref/golden/x310_full.json (test accuracy of the calibrated, exported model = the RTL) and
ref/golden/x310_stream.json; writes evidence/stage5/accuracy.md. No model is run here.

  python3 ref/x310/report_x310.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'ref/x310'))
import x310_data as xd  # noqa: E402  (TAG: which channel's files)
CL = ('noise', 'CW', 'LFM', 'BPSK')


def pct(v):
    return f'{100 * v:.1f}'


def main():
    sel = json.loads((ROOT / f'ref/x310/x310{xd.TAG}_selection.json').read_text())
    full = json.loads((ROOT / 'ref/golden/x310_full.json').read_text())
    stream = json.loads((ROOT / 'ref/golden/x310_stream.json').read_text())
    gold = json.loads((ROOT / 'ref/golden/x310_golden.json').read_text())
    bins = sel['snr_bins_db']
    lab = [f'{bins[i]:g}..{bins[i + 1]:g}' for i in range(len(bins) - 1)]
    out = ['# Stage 5 accuracy tables (generated by ref/x310/report_x310.py; every number is **model**)', '']
    out += ['## Per W, validation split (100,000 windows, 25,000 per class)', '',
            'Float = the best float64 run of that W; HGQ = the rule\'s pick for that W (D-S5-SEL). Accuracy in %.', '',
            '| W | model | EBOPs (train) | overall | SNR >= 10 dB | ' + ' | '.join(lab) + ' |',
            '|---|---|---|---|---|' + '---|' * len(lab)]
    for W, r in sorted(sel['per_w'].items(), key=lambda kv: int(kv[0])):
        fv = r['float_val']
        out.append(f"| {W} | float `{r['float_baseline']}` | - | {pct(fv['acc'])} | {pct(fv['acc_hi'])} | " +
                   ' | '.join(pct(v) for v in fv['acc_by_snr']) + ' |')
        p = r['pick']
        if p:
            flag = '' if r['pick_meets_hi'] else ' (SNR >= 10 dB criterion not met)'
            name = p['file'].split('/')[3] + '/' + p['file'].split('/')[-1].split('_acc')[0]
            out.append(f"| {W} | HGQ rule-1 pick `{name}`{flag} | {p['ebops']:,} | {pct(p['val']['acc'])} | {pct(p['val']['acc_hi'])} | " +
                       ' | '.join(pct(v) for v in p['val']['acc_by_snr']) + ' |')
        if 'rule1_pick' in sel and int(W) == sel['chosen']['w']:
            c = sel['chosen']
            name = c['file'].split('/')[3] + '/' + c['file'].split('/')[-1].split('_acc')[0]
            out.append(f"| {W} | **HGQ amended pick (chosen) `{name}`** | {c['ebops_train']:,} | {pct(c['val']['acc'])} | {pct(c['val']['acc_hi'])} | " +
                       ' | '.join(pct(v) for v in c['val']['acc_by_snr']) + ' |')
        if not p:
            out.append(f'| {W} | HGQ: no checkpoint within the margin | | | | ' + ' | ' * (len(lab) - 1) + ' |')
    out += ['', '### Per class at SNR >= 10 dB (validation, %)', '', '| W | model | ' + ' | '.join(CL) + ' |', '|---|---|' + '---|' * 4]
    for W, r in sorted(sel['per_w'].items(), key=lambda kv: int(kv[0])):
        out.append(f"| {W} | float | " + ' | '.join(pct(v) for v in r['float_val']['acc_by_class_hi']) + ' |')
        if r['pick']:
            out.append(f"| {W} | HGQ rule-1 pick | " + ' | '.join(pct(v) for v in r['pick']['val']['acc_by_class_hi']) + ' |')
        if 'rule1_pick' in sel and int(W) == sel['chosen']['w']:
            out.append(f"| {W} | HGQ amended pick (chosen) | " + ' | '.join(pct(v) for v in sel['chosen']['val']['acc_by_class_hi']) + ' |')
    out += ['', '### Float runs (validation, %)', '', '| W | run | input | overall | SNR >= 10 dB |', '|---|---|---|---|---|']
    for W, r in sorted(sel['per_w'].items(), key=lambda kv: int(kv[0])):
        for k, v in sorted(r['float_runs'].items()):
            out.append(f"| {W} | `{k}` | {'BFP' if v['bfp'] else 'raw int16'} | {pct(v['acc'])} | {pct(v['acc_hi'])} |")

    c = sel['chosen']
    fb = sel['chosen_float_baseline']
    tq = full['test_accuracy_quantized_calibrated']
    out += ['', f"## Chosen model, test split (100,000 windows; reported once, after the choice): W = {c['w']}", '',
            f"{sel['w_rule']}. Chosen checkpoint `{c['file']}`, {c['ebops_train']:,} EBOPs at training, "
            f"{gold['ebops_calibrated']:,} after trace_minmax calibration (the exported model); da4ml LUT estimate "
            f"{gold['da4ml_comb_cost_lut_est']:,.0f}.", '',
            '| model | overall | SNR >= 10 dB | ' + ' | '.join(lab) + ' |', '|---|---|---|' + '---|' * len(lab),
            f"| float64 `{fb['run']}` | {pct(fb['test']['acc'])} | {pct(fb['test']['acc_hi'])} | " + ' | '.join(pct(v) for v in fb['test']['acc_by_snr']) + ' |',
            f"| HGQ checkpoint (before calibration) | {pct(c['test_before_calibration']['acc'])} | {pct(c['test_before_calibration']['acc_hi'])} | " +
            ' | '.join(pct(v) for v in c['test_before_calibration']['acc_by_snr']) + ' |',
            f"| **HGQ exported (calibrated) = RTL** | **{pct(tq['acc'])}** | **{pct(tq['acc_hi'])}** | " + ' | '.join(pct(v) for v in tq['acc_by_snr']) + ' |',
            '', '### Confusion matrix of the exported model, test (rows true, columns predicted)', '',
            '| true \\ pred | ' + ' | '.join(CL) + ' |', '|---|' + '---|' * 4]
    for i, row in enumerate(tq['confusion_true_by_pred']):
        out.append(f'| {CL[i]} | ' + ' | '.join(f'{v:,}' for v in row) + ' |')
    out += ['', 'Per class, exported model, test (%): overall ' + ', '.join(f'{CL[i]} {pct(v)}' for i, v in enumerate(tq['acc_by_class'])) +
            '; at SNR >= 10 dB ' + ', '.join(f'{CL[i]} {pct(v)}' for i, v in enumerate(tq['acc_by_class_hi'])) + '.']
    out += ['', '## Continuous stream (information; sliding window, every sample)', '',
            f"`x310_data.make_stream(65536, seed 0)`: {stream['n_windows']:,} windows, {stream['pure_windows']:,} wholly inside one "
            f"pulse or gap, {stream['straddling_windows']:,} straddling an edge. Decisions of the exported model on the pure windows "
            f"agree with the label {pct(stream['pure_window_accuracy'])} % of the time (noise / CW / LFM / BPSK: " +
            ' / '.join(pct(v) for v in stream['pure_window_accuracy_by_class']) + ' %). The stream is a different draw '
            '(noise floor fixed at -40 dBFS, pulse SNR uniform over -5..25 dB), not the test distribution.', '']
    dst = ROOT / f'evidence/stage5/accuracy{xd.TAG}.md'
    dst.write_text('\n'.join(out))
    print('\n'.join(out))


if __name__ == '__main__':
    main()
