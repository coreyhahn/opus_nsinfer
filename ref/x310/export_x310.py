"""Freeze the chosen Stage 5 classifier and export it through da4ml (the Stage 0 flow; PLAN.md D-S5-BFP, D-S5-RTL).

  1. trace_minmax over the calibration set (the whole training split of the chosen W, model inputs) fixes
     the WRAP integer bits; the calibrated model is ref/golden/x310_hgq.keras.
  2. Full test set (every test window of that W, regenerated by x310_data.py and checked against the content
     hash in ref/x310/x310_split_meta.json): the RAW int16 window (the RTL port; BFP happens in RTL), the
     Keras float64 logits as per-lane two's-complement integers, and the decision np.argmax (first maximum).
     As hex under .scratch/ (x310_full_{in,out,dec}.hex; in = 8W hex digits, lane 0 = I_0 at the LSB, lane
     2k = I_k, 2k + 1 = Q_k); SHA-256 and accuracies in ref/golden/x310_full.json (D-S4-GOLDEN pattern).
  3. Committed golden set: N_GOLDEN windows of the full set (fixed seed, sorted indices):
     ref/golden/x310_golden.{npz,json}, x310_golden_{in,out,dec}.hex.
  4. Stream set (committed): a continuous 65,536-sample capture from x310_data.make_stream(seed 0); every
     one of its n - W + 1 windows through the Keras model: ref/golden/x310_stream_{in,out,dec}.hex (in = one
     sample per line, {Q, I}, I at the LSB), ref/golden/x310_stream.json (+ the label-agreement of windows
     wholly inside a pulse or a gap, for information).
  5. Pre-RTL check: Keras vs da4ml's DAIS interpreter on the traced CombLogic (traced from a 16-bit input,
     inputs_kif = (1, 0, 15), so the SAT / TRN input quantizer is part of it), bit for bit, on the full set
     and on the stream windows.
  6. rtl/gen/x310_clf_lanes.svh (W, BFP, logit lane layout for the argmax) and one da4ml Verilog project per
     latency cutoff, rtl/gen/x310_clf_lc<cutoff>/ (part xc7k410tffg900-2, 5.0 ns).

  python ref/x310/export_x310.py --cutoffs 2 3 5
  python ref/x310/export_x310.py --rtl-only --cutoffs 4          # more cutoffs from the frozen model
"""

import argparse
import json
import os
import shutil
import sys
from pathlib import Path

os.environ.setdefault('KERAS_BACKEND', 'jax')
import jax  # noqa: E402

jax.config.update('jax_enable_x64', True)
import keras  # noqa: E402
import numpy as np  # noqa: E402

keras.config.set_floatx('float64')

from da4ml.codegen import RTLModel  # noqa: E402
from da4ml.codegen.rtl.rtl_model import get_io_kifs  # noqa: E402
from da4ml.converter import trace_model  # noqa: E402
from da4ml.trace import comb_trace  # noqa: E402
from hgq.utils import trace_minmax  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'ref'))
sys.path.insert(0, str(ROOT / 'ref/x310'))
import x310_data as xd  # noqa: E402
from export_jsc import lanes_hex, sha256, to_lanes  # noqa: E402

NAME = 'x310_clf'
N_GOLDEN = 8192
SEED = 20261029
STREAM_N = 65536
IN_KIF = (1, 0, 15)


def windows_hex(x: np.ndarray) -> str:
    """int16 (n, 2W) -> one line of 8W hex digits per window, lane 0 at the LSB."""
    b = np.ascontiguousarray(x[:, ::-1]).astype('>u2').tobytes().hex()
    n = 8 * x.shape[1] // 2
    return ''.join(b[i:i + n] + '\n' for i in range(0, len(b), n))


def logits_and_dec(model, xin):
    z = np.asarray(model.predict(xin, batch_size=16384, verbose=0), np.float64)
    return z, np.argmax(z, axis=1)


def trace(model):
    """da4ml trace from 16-bit lanes. A lane whose kernel row HGQ pruned to zero is dropped from the core's
    port (kif (0, 0, 0)); every other lane must keep the full 16-bit input format."""
    sol = comb_trace(*trace_model(model, inputs_kif=IN_KIF))
    k_in, k_out = get_io_kifs(sol)
    full = (k_in[0] == IN_KIF[0]) & (k_in[1] == IN_KIF[1]) & (k_in[2] == IN_KIF[2])
    dropped = (k_in[0] == 0) & (k_in[1] == 0) & (k_in[2] == 0)
    assert np.all(full | dropped), 'core input lanes are neither 16-bit nor dropped'
    return sol, k_in, k_out


def core_offsets(k_in):
    """Offset of window lane j in the core's input port, -1 for a dropped lane."""
    used = k_in.sum(0) > 0
    off = np.cumsum(np.where(used, 16, 0)) - 16
    return np.where(used, off, -1), int(16 * used.sum())


def write_lanes_svh(W, bfp, k_in, k_out, path):
    coff, cw = core_offsets(k_in)
    k, i, f = (k_out[j].astype(np.int64) for j in range(3))
    w = k + i + f
    assert np.all(k == 1), 'argmax RTL assumes signed logit lanes'
    fmax = int(f.max())
    shift = fmax - f
    aw = int((w + shift).max())
    off = np.concatenate([[0], np.cumsum(w)[:-1]])
    lines = [
        '// Generated by ref/x310/export_x310.py from the frozen model (ref/golden/x310_hgq.keras). Do not edit.',
        '// Window: X_W complex samples, 2 X_W int16 lanes (lane 2k = I_k, 2k + 1 = Q_k, sample 0 oldest, lane 0',
        '// at the LSB). Logits: N_CLASS signed lanes, aligned to the finest LSB for the first-max argmax.',
        f'localparam int X_W = {W};',
        f'localparam int X_BFP = {int(bfp)};  // 1: block-floating-point shift in front of the core (D-S5-BFP)',
        f'localparam int X_S_MAX = {xd.S_MAX};',
        f'localparam int N_CLASS = {len(w)};',
        f'localparam int X_OUT_W = {int(w.sum())};',
        f'localparam int ARG_AW = {aw};  // aligned, sign-extended logit width',
        "localparam int LANE_OFF [N_CLASS] = '{" + ', '.join(str(int(x)) for x in off) + '};',
        "localparam int LANE_W   [N_CLASS] = '{" + ', '.join(str(int(x)) for x in w) + '};',
        "localparam int LANE_SH  [N_CLASS] = '{" + ', '.join(str(int(x)) for x in shift) + '};',
        '// Core input port: window lane j (after BFP) sits at IN_COFF[j] (16 bits), -1 = lane pruned by HGQ',
        '// (its kernel row is zero; da4ml drops it from the port; it still counts in the BFP mask).',
        f'localparam int X_CORE_IN_W = {cw};',
        "localparam int IN_COFF [2*X_W] = '{" + ', '.join(str(int(x)) for x in coff) + '};',
        '',
    ]
    path.write_text('\n'.join(lines))


def write_rtl(sol, cutoffs, rtl_root, hashes):
    for lc in cutoffs:
        name = f'{NAME}_lc{lc:g}'
        path = rtl_root / name
        if path.exists():
            shutil.rmtree(path)
        rtl = RTLModel(sol, NAME, path, latency_cutoff=lc, part_name='xc7k410tffg900-2', clock_period=5.0)
        rtl.write(metadata={'model_sha256': hashes['x310_hgq.keras'], 'golden_sha256_in_hex': hashes['x310_golden_in.hex']})
        md = json.loads((path / 'metadata.json').read_text())
        print(f'{name}: {md["latency"]} stages, est {md["cost"]:.0f} LUT, {md["reg_bits"]} FF')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--model', type=Path, default=ROOT / f'ref/runs/x310{xd.TAG}/chosen.keras')
    ap.add_argument('--selection', type=Path, default=ROOT / f'ref/x310/x310{xd.TAG}_selection.json')
    ap.add_argument('--golden', type=Path, default=ROOT / 'ref/golden')
    ap.add_argument('--rtl-root', type=Path, default=ROOT / 'rtl/gen')
    ap.add_argument('--scratch', type=Path, default=ROOT / '.scratch')
    ap.add_argument('--cutoffs', type=float, nargs='+', default=[])
    ap.add_argument('--rtl-only', action='store_true', help='emit RTL from the frozen model in --golden; never rewrite golden files')
    a = ap.parse_args()
    for k in ('model', 'selection', 'golden', 'rtl_root', 'scratch'):
        setattr(a, k, getattr(a, k).resolve())
    g = a.golden

    if a.rtl_only:
        meta = json.loads((g / 'x310_golden.json').read_text())
        for p, h in meta['sha256'].items():
            assert sha256(g / p) == h, f'{p} does not match x310_golden.json'
        sol, k_in, k_out = trace(keras.models.load_model(g / 'x310_hgq.keras'))
        z = np.load(g / 'x310_golden.npz')
        assert np.array_equal(k_out, z['out_kif']), 'traced output format differs from golden'
        write_rtl(sol, a.cutoffs, a.rtl_root, meta['sha256'])
        return

    sel = json.loads(a.selection.read_text())
    W, bfp = int(sel['chosen']['w']), int(sel['chosen']['bfp'])
    smeta = json.loads((xd.META).read_text())
    tr = xd.load(W, 'train')
    te = xd.load(W, 'test')
    for split, d in (('train', tr), ('test', te)):
        assert xd.content_sha256(d) == smeta['files'][f'x310_w{W}_{split}.npz']['content_sha256'], f'{split} split differs from its meta'

    model = keras.models.load_model(a.model)
    ebops = int(trace_minmax(model, xd.model_input(tr['x'], bool(bfp)), batch_size=16384))
    del tr
    model.save(g / 'x310_hgq.keras')

    # ---- full test set
    xin = xd.model_input(te['x'], bool(bfp))
    logit, dec = logits_and_dec(model, xin)
    sol, k_in, k_out = trace(model)
    n_interp_mis = int(np.sum(np.any(sol.predict(xin) != logit, axis=1)))
    out_lanes, out_w = to_lanes(logit, k_out)
    a.scratch.mkdir(parents=True, exist_ok=True)
    full = {s: a.scratch / f'x310_full_{s}.hex' for s in ('in', 'out', 'dec')}
    full['in'].write_text(windows_hex(te['x']))
    full['out'].write_text('\n'.join(lanes_hex(out_lanes, out_w)) + '\n')
    full['dec'].write_text(''.join(f'{v:x}\n' for v in dec))
    y, snr = te['y'], te['snr_db']
    ok = dec == y
    bins = np.arange(-5.0, 25.01, 2.5)
    b = np.clip(np.digitize(snr, bins) - 1, 0, len(bins) - 2)
    conf = np.zeros((4, 4), np.int64)
    np.add.at(conf, (y, dec), 1)
    acc = {'acc': float(ok.mean()), 'acc_hi': float(ok[snr >= 10].mean()),
           'snr_bins_db': bins.tolist(), 'acc_by_snr': [float(ok[b == i].mean()) for i in range(len(bins) - 1)],
           'acc_by_class': [float(ok[y == c].mean()) for c in range(4)],
           'acc_by_class_hi': [float(ok[(y == c) & (snr >= 10)].mean()) for c in range(4)],
           'confusion_true_by_pred': conf.tolist()}
    fmeta = {'n': int(len(y)), 'w': W, 'bfp': bfp, 'test_split': f'ref/data/x310/x310_w{W}_test.npz',
             'test_content_sha256': smeta['files'][f'x310_w{W}_test.npz']['content_sha256'],
             'files': {s: str(p.relative_to(ROOT)) for s, p in full.items()},
             'sha256': {s: sha256(p) for s, p in full.items()},
             'in_hex_digits': 8 * W, 'test_accuracy_quantized_calibrated': acc,
             'keras_vs_dais_interp_mismatching_vectors': n_interp_mis}
    (g / 'x310_full.json').write_text(json.dumps(fmeta, indent=1) + '\n')

    # ---- committed golden subset
    idx = np.sort(np.random.default_rng(SEED).choice(len(y), N_GOLDEN, replace=False))
    (g / 'x310_golden_in.hex').write_text(windows_hex(te['x'][idx]))
    (g / 'x310_golden_out.hex').write_text('\n'.join(lanes_hex(out_lanes[idx], out_w)) + '\n')
    (g / 'x310_golden_dec.hex').write_text(''.join(f'{v:x}\n' for v in dec[idx]))
    np.savez_compressed(g / 'x310_golden.npz', idx=idx, x=te['x'][idx], y=y[idx], snr_db=snr[idx],
                        out_lanes=out_lanes[idx].astype(np.uint32), dec=dec[idx].astype(np.uint8), out_kif=k_out)

    # ---- stream set
    ys, lab = xd.make_stream(STREAM_N, 0)
    sw = xd.stream_windows(ys, W)
    sl, sd = logits_and_dec(model, xd.model_input(sw, bool(bfp)))
    s_interp_mis = int(np.sum(np.any(sol.predict(xd.model_input(sw, bool(bfp))) != sl, axis=1)))
    s_lanes, _ = to_lanes(sl, k_out)
    su = ys.astype(np.int64) & 0xFFFF
    (g / 'x310_stream_in.hex').write_text(''.join(f'{(q << 16) | i:08x}\n' for i, q in su.tolist()))
    (g / 'x310_stream_out.hex').write_text('\n'.join(lanes_hex(s_lanes, out_w)) + '\n')
    (g / 'x310_stream_dec.hex').write_text(''.join(f'{v:x}\n' for v in sd))
    from numpy.lib.stride_tricks import sliding_window_view
    lw = sliding_window_view(lab, W)
    pure = np.all(lw == lw[:, :1], axis=1)
    wl = lw[:, 0]
    smeta_out = {'n_samples': STREAM_N, 'n_windows': int(len(sd)), 'generator': 'x310_data.make_stream(65536, seed=0)',
                 'sample_label_counts': np.bincount(lab, minlength=4).tolist(),
                 'pure_windows': int(pure.sum()), 'pure_window_accuracy': float(np.mean(sd[pure] == wl[pure])),
                 'pure_window_accuracy_by_class': [float(np.mean(sd[pure & (wl == c)] == c)) for c in range(4)],
                 'straddling_windows': int((~pure).sum()), 'decision_counts': np.bincount(sd, minlength=4).tolist(),
                 'keras_vs_dais_interp_mismatching_vectors': s_interp_mis,
                 'sha256': {f'x310_stream_{s}.hex': sha256(g / f'x310_stream_{s}.hex') for s in ('in', 'out', 'dec')}}
    (g / 'x310_stream.json').write_text(json.dumps(smeta_out, indent=1) + '\n')

    meta = {
        'model_source': str(a.model), 'selection': str(a.selection.relative_to(ROOT)), 'w': W, 'bfp': bfp,
        'n_vectors': N_GOLDEN, 'n_full': int(len(y)), 'subset': f'numpy default_rng({SEED}).choice(n_full, {N_GOLDEN}), sorted',
        'decision_rule': 'np.argmax over the logits (first maximum wins)', 'ebops_calibrated': ebops,
        'ebops_train': sel['chosen']['ebops_train'], 'in_kif': IN_KIF, 'in_lanes': 2 * W, 'in_width_bits': 32 * W,
        'core_in_width_bits': core_offsets(k_in)[1], 'pruned_input_lanes': np.flatnonzero(k_in.sum(0) == 0).tolist(),
        'out_width_bits': int(out_w.sum()), 'out_lane_widths': out_w.tolist(), 'out_kif': k_out.tolist(),
        'da4ml_comb_cost_lut_est': float(sol.cost), 'da4ml_comb_latency': [float(v) for v in sol.latency],
        'keras_vs_dais_interp_mismatching_vectors_full': n_interp_mis,
        'keras_vs_dais_interp_mismatching_vectors_stream': s_interp_mis,
        'test_accuracy_quantized_calibrated': acc['acc'], 'test_accuracy_quantized_calibrated_snr_ge_10': acc['acc_hi'],
        'golden_subset_accuracy': float(np.mean(dec[idx] == y[idx])),
        'sha256': {p: sha256(g / p) for p in ('x310_golden.npz', 'x310_golden_in.hex', 'x310_golden_out.hex',
                                              'x310_golden_dec.hex', 'x310_hgq.keras')},
    }
    (g / 'x310_golden.json').write_text(json.dumps(meta, indent=1) + '\n')
    print(json.dumps({k: v for k, v in meta.items() if k not in ('out_kif',)}, indent=1))
    print(json.dumps({k: v for k, v in smeta_out.items() if k != 'sha256'}, indent=1))
    write_lanes_svh(W, bfp, k_in, k_out, a.rtl_root / f'{NAME}_lanes.svh')
    write_rtl(sol, a.cutoffs, a.rtl_root, meta['sha256'])


if __name__ == '__main__':
    main()
