"""Golden decisions and the logit-lane layout for the Stage 1 harness.

From the committed golden logits (`ref/golden/jsc_golden.npz`, the Keras
float64 outputs as per-lane two's-complement integers):
  - `ref/golden/jsc_golden_argmax.hex`: one hex digit per test vector,
    np.argmax of the logit values (first maximum wins), the class the
    harness must drive on its pins;
  - `rtl/jsc_out_lanes.svh`: lane offsets, widths and alignment shifts the
    argmax RTL uses (generated, never typed by hand);
  - hashes and the decision accuracy appended to `ref/golden/jsc_golden_argmax.json`.

  uv run python ref/export_argmax.py
"""

import hashlib
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
GOLD = ROOT / 'ref/golden'


def main():
    meta = json.loads((GOLD / 'jsc_golden.json').read_text())
    npz = np.load(GOLD / 'jsc_golden.npz')
    assert hashlib.sha256((GOLD / 'jsc_golden.npz').read_bytes()).hexdigest() == meta['sha256']['jsc_golden.npz']
    k, i, f = (npz['out_kif'][j].astype(np.int64) for j in range(3))
    w = k + i + f
    lanes = npz['out_lanes'].astype(np.int64)
    signed = np.where((k == 1) & (lanes >= (1 << (w - 1))), lanes - (1 << w), lanes)
    vals = signed * 2.0 ** (-f)
    dec = np.argmax(vals, axis=1)
    acc = float(np.mean(dec == npz['y']))
    assert abs(acc - meta['test_accuracy_quantized']) < 1e-12, (acc, meta['test_accuracy_quantized'])
    ties = int(np.sum(np.sum(vals == vals.max(axis=1, keepdims=True), axis=1) > 1))

    hexf = GOLD / 'jsc_golden_argmax.hex'
    hexf.write_text(''.join(f'{d:x}\n' for d in dec))

    # Alignment: every lane shifted onto the finest LSB, sign-extended to AW bits.
    fmax = int(f.max())
    shift = fmax - f
    aw = int((w + shift).max() + (0 if k.min() == 1 else 1))
    off = np.concatenate([[0], np.cumsum(w)[:-1]])
    assert np.all(k == 1), 'argmax RTL assumes signed logit lanes'
    lines = [
        '// Generated by ref/export_argmax.py from ref/golden/jsc_golden.json. Do not edit.',
        f'localparam int N_CLASS = {len(w)};',
        f'localparam int OUT_W = {int(w.sum())};',
        f'localparam int ARG_AW = {aw};  // aligned, sign-extended logit width',
        'localparam int LANE_OFF [N_CLASS] = \'{' + ', '.join(str(int(x)) for x in off) + '};',
        'localparam int LANE_W   [N_CLASS] = \'{' + ', '.join(str(int(x)) for x in w) + '};',
        'localparam int LANE_SH  [N_CLASS] = \'{' + ', '.join(str(int(x)) for x in shift) + '};',
        '',
    ]
    (ROOT / 'rtl/jsc_out_lanes.svh').write_text('\n'.join(lines))

    rep = {
        'source': 'ref/golden/jsc_golden.npz', 'source_sha256': meta['sha256']['jsc_golden.npz'],
        'rule': 'np.argmax over logit values (first maximum wins)',
        'n': int(len(dec)), 'accuracy': acc, 'vectors_with_tied_maximum': ties,
        'class_counts': np.bincount(dec, minlength=len(w)).tolist(),
        'jsc_golden_argmax.hex_sha256': hashlib.sha256(hexf.read_bytes()).hexdigest(),
    }
    (GOLD / 'jsc_golden_argmax.json').write_text(json.dumps(rep, indent=1) + '\n')
    print(json.dumps(rep, indent=1))


if __name__ == '__main__':
    main()
