"""Write the Stage 6 desk-card command files (sw/bcu/desk.sh run <file>; register maps rtl/s3/s3_regmap.md and
rtl/s6/s6_regmap.md). The files are generated because the diag snapshot is 128 words; the generator is the source.

  python3 sw/bcu/gen_s6_cmd.py          -> sw/bcu/s6_status.cmd, sw/bcu/s6_measure.cmd, sw/bcu/s6_retrain.cmd
  python3 sw/bcu/gen_s6_cmd.py --nvec 131072 --tag s6d5   -> s6d5_measure.cmd (d = 5; its status / retrain files equal the s6_ ones)

s6_status.cmd   board / GT / link status and the diag snapshot, no waiting (bring-up checklist).
s6_measure.cmd  docs/PLAN.md D-S6-MEAS, in order: status; wait for block lock on both ends; one-way probe over
                the cable (GAP 63 equivalent: period 63, then back to back), histogram bases 0 and 32; the Stage 3
                runs (echo GAP 63, decode GAP 63, decode GAP 7 with the flag-RAM sample, as s3_measure.cmd / s4_measure.cmd);
                link counters after the runs; then near-end PMA and near-end PCS loopback on end A with the probe
                (A TX -> A RX inside the GTY, no cable), and back to the cable.
"""
import argparse
from pathlib import Path

HERE = Path(__file__).resolve().parent
DIAG = 0x1000
LIVE = DIAG + 0x400
NAMES = {0: 'a_lock', 1: 'a_n_lock', 2: 'a_n_unlock', 3: 'a_n_slip', 4: 'a_n_sh_bad', 5: 'a_n_idle_bad', 6: 'a_n_data',
         7: 'a_n_dsk_ovf', 8: 'a_n_hv_dv', 9: 'a_n_bufrst', 10: 'a_bufstat', 11: 'a_n_chk_ok', 12: 'a_n_chk_bad',
         16: 'b_lock', 17: 'b_n_lock', 18: 'b_n_unlock', 19: 'b_n_slip', 20: 'b_n_sh_bad', 21: 'b_n_idle_bad', 22: 'b_n_data',
         23: 'b_n_dsk_ovf', 24: 'b_n_hv_dv', 25: 'b_n_bufrst', 26: 'b_bufstat', 27: 'b_n_chk_ok', 28: 'b_n_chk_bad',
         32: 'pa_n_tx', 33: 'pa_n_rx', 34: 'pa_n_bad', 35: 'pa_lat_min', 36: 'pa_lat_max', 37: 'pa_lat_sum_lo', 38: 'pa_lat_sum_hi',
         40: 'pb_n_tx', 41: 'pb_n_rx', 42: 'pb_n_bad', 43: 'pb_lat_min', 44: 'pb_lat_max', 45: 'pb_lat_sum_lo', 46: 'pb_lat_sum_hi',
         48: 'tsc'}


def snap(hist=True):
    out = ['w 0x1010 1', 'sleep 0.05', 'r 0x1010 d_snap_busy']
    for k, n in NAMES.items():
        out.append(f'r 0x{LIVE + 4 * k:04x} {n}')
    if hist:
        for k in range(32):
            out.append(f'r 0x{LIVE + 4 * (64 + k):04x} pa_hist{k}')
            out.append(f'r 0x{LIVE + 4 * (96 + k):04x} pb_hist{k}')
    return out


def status():
    return ['r 0x000 ID', 'r 0x0F0 NVEC', 'r 0x0F4 DEC_LAT', 'r 0x0FC N_DET', 'r 0x100 DW', 'r 0x020 BOARD',
            'r 0x024 LINK', 'r 0x028 FREQ_A', 'r 0x02C FREQ_B', 'r 0x1000 D_ID', 'r 0x1014 D_PARAMS']


def probe(name, period, hbase, secs=1.0):
    return [f'echo probe {name} period={period} hbase={hbase}', 'w 0x1004 2', 'sleep 0.01', 'w 0x1004 0',
            f'w 0x1008 {period}', f'w 0x100C {hbase}', 'w 0x1004 1', f'sleep {secs}', 'w 0x1004 0', 'sleep 0.05',
            *snap(), f'echo probe_end {name}']


def s3_runs(nvec_tail):
    out = ['w 0x004 0x30', 'w 0x004 0x00', 'w 0x00C 0']
    for name, mode, gap, extra in (('echo_gap63', 0x02, 63, []), ('decode_gap63', 0x00, 63, []),
                                   ('decode_gap7', 0x00, 7, ['flips 0 4096', f'flips {nvec_tail} 4096'])):
        out += [f'echo run {name}', f'w 0x008 {gap}', f'w 0x004 0x{mode:02x}', f'w 0x004 0x{mode | 1:02x}',
                'wait 0x010 0x1 0x1 120', '@stats', 'hist 256', *extra, f'w 0x004 0x{mode:02x}', 'wait 0x010 0x1 0x0 10']
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--nvec', type=int, default=464428, help='shots in the ROM (the flag sample reads the last 4096)')
    ap.add_argument('--tag', default='s6')
    a = ap.parse_args()
    hdr = [f'# GENERATED by sw/bcu/gen_s6_cmd.py --nvec {a.nvec}; edit the generator, not this file.']
    st = hdr + ['# Stage 6 status, no waiting (bring-up checklist)', 'echo board'] + status() + ['echo diag'] + snap(hist=False)
    (HERE / f'{a.tag}_status.cmd').write_text('\n'.join(st) + '\n')
    m = hdr + ['# Stage 6 silicon run: docs/PLAN.md D-S6-MEAS', 'echo board'] + status()
    m += ['wait 0x024 0x00000101 0x00000101 30', 'r 0x024 LINK', 'w 0x004 0x30', 'w 0x004 0x00', 'w 0x1004 2', 'w 0x1004 0']
    m += probe('cable_p63_b0', 63, 0) + probe('cable_p63_b32', 63, 32) + probe('cable_p0_b0', 0, 0)
    m += s3_runs(a.nvec - 4096)
    m += ['echo after_runs', 'r 0x024 LINK', 'r 0x028 FREQ_A', 'r 0x02C FREQ_B'] + snap(hist=False)
    # near-end PMA loopback (LOOPBACK = 010) and near-end PCS loopback (001) on end A only (A TX -> A RX inside the
    # GTY, no cable), with the probe at period 63 and back to back
    for nm, code in (('pmaloop_a', 2), ('pcsloop_a', 1)):
        m += [f'echo loopback_a_on {nm}', f'w 0x020 0x{0x200 | code:03x}', 'sleep 0.2', f'w 0x020 0x{code:03x}', 'sleep 1',
              'wait 0x024 0x00000001 0x00000001 30', 'r 0x024 LINK']
        m += probe(f'{nm}_p63_b0', 63, 0) + probe(f'{nm}_p0_b0', 0, 0)
    m += ['echo loopback_off', 'w 0x020 0x200', 'sleep 0.2', 'w 0x020 0x000', 'sleep 1',
          'wait 0x024 0x00000101 0x00000101 30', 'r 0x024 LINK', 'w 0x004 0x30', 'w 0x004 0x00', 'r 0x024 LINK_CLEAN']
    (HERE / f'{a.tag}_measure.cmd').write_text('\n'.join(m) + '\n')
    # re-train: gtwiz_reset_all (BOARD[8]) pulse, i.e. QPLLs, TX and RX resets, new block lock
    rt = hdr + ['# Stage 6 re-train: BOARD[8] = gtwiz_reset_all pulse, then wait for block lock', 'echo board'] + status()
    rt += ['echo retrain', 'w 0x020 0x100', 'sleep 0.5', 'w 0x020 0x000', 'sleep 3', 'wait 0x024 0x00000101 0x00000101 30',
           'r 0x024 LINK', 'w 0x004 0x30', 'w 0x004 0x00', 'r 0x024 LINK_CLEAN', 'echo diag'] + snap(hist=False)
    (HERE / f'{a.tag}_retrain.cmd').write_text('\n'.join(rt) + '\n')
    print(f'wrote {HERE}/{a.tag}_status.cmd {HERE}/{a.tag}_measure.cmd {HERE}/{a.tag}_retrain.cmd')


if __name__ == '__main__':
    main()
